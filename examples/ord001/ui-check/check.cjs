const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

const base = process.argv[2] || 'http://127.0.0.1:8024';
const evidence = process.argv[3];
if (!evidence) throw new Error('Usage: node check.cjs URL EVIDENCE_DIRECTORY');
const results = [];
const errors = [];

(async () => {
  await fs.mkdir(evidence, { recursive: true });
  const browser = await chromium.launch(process.env.PLAYWRIGHT_CHROME ? { executablePath: process.env.PLAYWRIGHT_CHROME, headless: true } : { channel: 'chrome', headless: true });
  const watch = page => {
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error' && !message.text().includes('401')) errors.push(message.text()); });
    page.on('response', response => { if (response.status() >= 500) errors.push(`${response.status()} ${response.url()}`); });
  };
  const shot = async (page, name) => {
    await page.evaluate(() => window.scrollTo(0, 0));
    return page.screenshot({ path: path.join(evidence, name), fullPage: true });
  };
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, colorScheme: 'light' });
    const customer = await context.newPage();
    const reviewer = await context.newPage();
    watch(customer); watch(reviewer);
    const state = async () => (await context.request.get(`${base}/api/customer/state`)).json();
    const send = async text => { await customer.locator('#input').fill(text); await customer.locator('#send').click(); };
    const reset = async () => {
      if (!await reviewer.locator('#reset').isVisible()) await reviewer.locator('#meta').click();
      await reviewer.locator('#reset').click();
      await reviewer.locator('#reset-dialog').waitFor();
      await reviewer.locator('#reset-confirm').click();
      await reviewer.waitForFunction(() => !document.getElementById('reset-dialog').open);
      await customer.locator('#tickets .empty').waitFor();
      const cleared = await state();
      assert.equal(cleared.tickets.length, 0);
      assert.equal(cleared.confirmation, null);
    };
    await customer.goto(base);
    await customer.locator('#login-choices button').first().waitFor();
    await shot(customer, 'customer-entry.png');
    await customer.getByRole('button', { name: '模拟顾客 U001', exact: true }).click();
    await customer.locator('#app').waitFor();
    await reviewer.goto(`${base}/review`);
    await reviewer.getByRole('button', { name: '模拟审批员 R001', exact: true }).click();
    await reviewer.locator('#app').waitFor();
    await reset();
    await shot(customer, 'customer-workspace.png');
    await customer.locator('#order-search').fill('ORD005');
    assert.equal(await customer.locator('#orders .order').count(), 1);
    assert((await customer.locator('#orders').innerText()).includes('30:01'));
    await customer.locator('#order-search').fill('');
    assert.equal(await customer.locator('#orders .order').count(), 3);
    await customer.locator('#more-orders').click();
    assert.equal(await customer.locator('#orders .order').count(), 8);
    await customer.locator('#more-orders').click();
    assert.equal(await customer.locator('#orders .order').count(), 3);
    results.push({ case: 'Order search and expand/collapse', status: 'passed' });
    await customer.locator('[data-open-demo]:visible').first().click();
    assert((await customer.locator('#policy-details').innerText()).includes('demo-v1'));
    await customer.keyboard.press('Escape');
    assert.equal(await customer.locator('#demo-dialog').isVisible(), false);
    results.push({ case: 'Demo information dialog and Escape', status: 'passed' });

    await send('我的外卖 ORD001 迟到了，可以申请补偿吗？');
    await customer.locator('#confirm').waitFor();
    let data = await state();
    assert.equal(data.tickets.length, 0);
    assert.equal(data.confirmation.late_seconds, 3000);
    assert.equal(data.confirmation.proposed_coupon_yuan, 10);
    const conversation = await customer.locator('#messages').innerText();
    assert(!conversation.includes('模拟模型'), 'Customer conversation exposes model metadata');
    assert(!conversation.includes('demo-v1'), 'Customer conversation exposes policy version');
    assert.match(await customer.locator('#journey .current strong').innerText(), /确认/);
    await shot(customer, 'p01-before-confirm.png');
    await customer.locator('#confirm-yes').click();
    await customer.locator('#tickets .badge-pending').waitFor();
    data = await state();
    const approvedId = data.tickets[0].ticket_id;
    assert.match(await customer.locator('#journey .current strong').innerText(), /审核|处理中|等待处理|商家处理/);
    await reviewer.locator('#pending .ticket-pending').waitFor();
    assert((await reviewer.locator('#pending').innerText()).includes(approvedId));
    await shot(reviewer, 'p01-review-pending.png');
    await reviewer.locator('#pending textarea').fill('已核实晚到 50 分钟，同意演示补偿。');
    await reviewer.getByRole('button', { name: /^(批准|通过)$/ }).click();
    await reviewer.locator('#decided-panel').waitFor();
    await customer.locator('#tickets .badge-approved').waitFor();
    data = await state();
    assert.equal(data.tickets[0].ticket_id, approvedId);
    assert.equal(data.tickets[0].coupon_issued_yuan, 10);
    assert((await customer.locator('#tickets').innerText()).includes('已核实晚到 50 分钟，同意演示补偿。'));
    assert.match(await customer.locator('#journey .current strong').innerText(), /结果|完成/);
    await shot(customer, 'p01-customer-approved.png');
    await shot(reviewer, 'p01-review-approved.png');
    results.push({ case: 'P01 approve, same ticket, note visible, live progress', status: 'passed', ticket_id: approvedId });

    await reset();
    await send('ORD005');
    await customer.locator('#confirm').waitFor();
    await customer.locator('#confirm-yes').click();
    await reviewer.locator('#pending textarea').waitFor();
    const followupId = (await state()).tickets[0].ticket_id;
    await reviewer.locator('#pending textarea').fill('请补充订单送达后的情况。');
    await reviewer.locator('[data-action="request-info"]').click();
    const information = customer.locator('textarea[data-information]');
    await information.waitFor();
    data = await state();
    assert.equal(data.tickets[0].status, 'needs_info');
    assert.equal(data.tickets[0].coupon_issued_yuan, null);
    assert.equal(data.tickets[0].information_request, '请补充订单送达后的情况。');
    await information.fill('餐品送达时已经凉了，包装完整。');
    await information.focus();
    await information.evaluate(field => field.setSelectionRange(2, 5));
    const refreshResponse = await customer.waitForResponse(response => response.url() === `${base}/api/customer/state` && response.request().method() === 'GET');
    await refreshResponse.finished();
    await customer.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert.equal(await information.inputValue(), '餐品送达时已经凉了，包装完整。');
    assert(await information.evaluate(field => document.activeElement === field), 'Polling lost the reply field focus');
    assert.deepEqual(await information.evaluate(field => [field.selectionStart, field.selectionEnd]), [2, 5]);
    await shot(customer, 'customer-information-request.png');
    await customer.locator('[data-action="submit-information"]').click();
    await reviewer.locator('#pending .customer-information').waitFor();
    assert((await reviewer.locator('#pending .customer-information').innerText()).includes('餐品送达时已经凉了'));
    data = await state();
    assert.equal(data.tickets.length, 1);
    assert.equal(data.tickets[0].ticket_id, followupId);
    assert.equal(data.tickets[0].status, 'pending');
    assert.equal(data.tickets[0].late_seconds, 1801);
    assert.equal(data.tickets[0].policy_version, 'demo-v1');
    assert.equal(data.tickets[0].coupon_issued_yuan, null);
    await shot(reviewer, 'merchant-information-received.png');
    await reviewer.locator('#pending textarea').fill('已核实补充信息，同意本次申请。');
    await reviewer.getByRole('button', { name: /^(批准|通过)$/ }).click();
    await customer.locator('#tickets .badge-approved').waitFor();
    data = await state();
    assert.equal(data.tickets[0].ticket_id, followupId);
    assert.equal(data.tickets[0].coupon_issued_yuan, 10);
    const customerHistory = customer.locator('#tickets details[data-ticket-history]').first();
    await customerHistory.locator('summary').click();
    await customerHistory.locator('.history-event').nth(3).waitFor();
    const historyText = await customerHistory.innerText();
    assert(historyText.includes('请补充订单送达后的情况。'));
    assert(historyText.includes('餐品送达时已经凉了，包装完整。'));
    assert(!historyText.includes('information_requested'));
    assert(!historyText.includes('reviewer:R001'));
    const merchantHistory = reviewer.locator('#decided details[data-ticket-history]').first();
    await merchantHistory.locator('summary').click();
    await merchantHistory.locator('.history-event').nth(3).waitFor();
    assert((await merchantHistory.innerText()).includes('餐品送达时已经凉了，包装完整。'));
    await shot(customer, 'customer-information-approved.png');
    results.push({ case: 'Information request, draft preservation, same ticket resumes and is approved', status: 'passed', ticket_id: followupId });

    await reset();
    await send('ORD001');
    await customer.locator('#confirm').waitFor();
    await customer.locator('#confirm-yes').click();
    await customer.locator('#tickets .badge-pending').waitFor();
    await reviewer.locator('#pending textarea').waitFor();
    await reviewer.locator('#pending textarea').fill('独立驳回用例：不发放模拟券。');
    await reviewer.getByRole('button', { name: /^(驳回|拒绝)$/ }).click();
    await customer.locator('#tickets .badge-rejected').waitFor();
    data = await state();
    assert.equal(data.tickets[0].coupon_issued_yuan, null);
    assert((await customer.locator('#tickets').innerText()).includes('独立驳回用例'));
    await shot(customer, 'p01-customer-rejected.png');
    results.push({ case: 'P01 independent reject, no coupon, note visible', status: 'passed' });

    await reset();
    await send('ORD008');
    await customer.locator('#confirm').waitFor();
    await customer.locator('#confirm-no').click();
    await customer.waitForFunction(() => !document.getElementById('send').disabled);
    assert.equal((await state()).tickets.length, 0);
    assert.equal((await state()).confirmation, null);
    results.push({ case: 'Cancel confirmation creates no ticket', status: 'passed' });
    await send('我的外卖迟到了，可以申请补偿吗？');
    await customer.waitForFunction(() => !document.getElementById('send').disabled);
    assert((await customer.locator('#messages').innerText()).includes('订单号'));
    await send('ORD101');
    await customer.waitForFunction(() => !document.getElementById('send').disabled);
    data = await state();
    assert.equal(data.tickets.length, 0);
    assert.equal(data.confirmation, null);
    assert(!(await customer.locator('#messages').innerText()).includes('66'));
    results.push({ case: 'P03 asks for order, refuses other owner without leaking facts', status: 'passed' });

    await customer.locator('#theme-toggle').click();
    assert.equal(await customer.locator('html').getAttribute('data-theme'), 'dark');
    await shot(customer, 'customer-dark.png');
    await customer.reload();
    await customer.locator('#app').waitFor();
    assert.equal(await customer.locator('html').getAttribute('data-theme'), 'dark');
    await reviewer.locator('#theme-toggle').click();
    await shot(reviewer, 'review-dark.png');
    results.push({ case: 'Theme switching and per-browser persistence', status: 'passed' });
    assert(await customer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desktop overflow');
    await context.close();

    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, colorScheme: 'light', deviceScaleFactor: 1 });
    const mobile = await mobileContext.newPage(); watch(mobile);
    await mobile.goto(base);
    await mobile.getByRole('button', { name: '模拟顾客 U001', exact: true }).click();
    await mobile.locator('#app').waitFor();
    await mobile.locator('#input').fill('ORD005');
    await mobile.locator('#send').click();
    await mobile.locator('#confirm').waitFor();
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Customer mobile confirmation overflow');
    await shot(mobile, 'customer-mobile.png');
    await mobile.locator('#confirm-yes').click();
    await mobile.locator('#tickets .badge-pending').waitFor();
    await mobile.goto(`${base}/review`);
    await mobile.getByRole('button', { name: '模拟审批员 R001', exact: true }).click();
    await mobile.locator('#app').waitFor();
    await mobile.locator('#pending textarea').waitFor();
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Reviewer mobile pending ticket overflow');
    await shot(mobile, 'review-mobile.png');
    await mobile.locator('#pending textarea').fill('手机端核对：本次不发放补偿券。');
    await mobile.getByRole('button', { name: /^(驳回|拒绝)$/ }).click();
    await mobile.locator('#decided-panel').waitFor();
    await mobile.goto(base);
    await mobile.locator('#app').waitFor();
    await mobile.locator('#tickets .badge-rejected').waitFor();
    const mobileState = await (await mobileContext.request.get(`${base}/api/customer/state`)).json();
    assert.equal(mobileState.tickets.length, 1);
    assert.equal(mobileState.tickets[0].order_id, 'ORD005');
    assert.equal(mobileState.tickets[0].late_seconds, 1801);
    assert.equal(mobileState.tickets[0].coupon_issued_yuan, null);
    assert((await mobile.locator('#tickets').innerText()).includes('手机端核对'));
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Customer mobile result overflow');
    await shot(mobile, 'customer-mobile-result.png');
    results.push({ case: '390px confirmation, merchant decision and customer result', status: 'passed' });
    await mobileContext.close();
    assert.deepEqual(errors, []);
    const report = { base, checked_at: new Date().toISOString(), results, errors, summary: { passed: results.length, failed: 0 } };
    await fs.writeFile(path.join(evidence, 'browser-results.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } catch (error) {
    await fs.writeFile(path.join(evidence, 'browser-failure.json'), JSON.stringify({ results, errors, failure: error.stack }, null, 2));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
